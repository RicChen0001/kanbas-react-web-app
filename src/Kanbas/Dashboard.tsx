import React, { useState } from "react";
import { Link } from "react-router-dom";
import { useSelector, useDispatch } from "react-redux";
import { enroll, unenroll } from "./Enrollments/enrollmentsReducer";
import { RootState } from "./store";
import { User } from "./Enrollments/types";

export default function Dashboard({ 
  courses, 
  course, 
  setCourse, 
  addNewCourse,
  deleteCourse, 
  updateCourse 
}: {
  courses: any[]; 
  course: any; 
  setCourse: (course: any) => void;
  addNewCourse: () => void; 
  deleteCourse: (course: any) => void;
  updateCourse: () => void; 
}) {
  const dispatch = useDispatch();
  const currentUser = useSelector((state: RootState) => 
    state.accountReducer.currentUser
  ) as User | null;
  const enrollments = useSelector((state: RootState) => 
    state.enrollmentsReducer.enrollments
  );
  const [showAllCourses, setShowAllCourses] = useState(false);

  const isEnrolled = (courseId: string) => {
    return enrollments.some(
      e => e.userId === currentUser?._id && e.courseId === courseId
    );
  };

  const handleEnrollment = (courseId: string) => {
    if (isEnrolled(courseId)) {
      dispatch(unenroll({ userId: currentUser?._id, courseId }));
    } else {
      dispatch(enroll({ userId: currentUser?._id, courseId }));
    }
  };

  const displayedCourses = currentUser?.role === "FACULTY" 
    ? courses 
    : showAllCourses 
      ? courses 
      : courses.filter(course => isEnrolled(course._id));

  return (
    <div id="wd-dashboard">
      <h1 id="wd-dashboard-title">Dashboard</h1>
      <hr />
      {currentUser?.role === "FACULTY" && (
        <>
          <h5>New Course
            <button className="btn btn-primary float-end"
                    id="wd-add-new-course-click"
                    onClick={addNewCourse}>
                    Add
            </button>
            <button className="btn btn-warning float-end me-2"
                    onClick={updateCourse}
                    id="wd-update-course-click">
                    Update
            </button>
          </h5><br />
          <input value={course.name} 
                 className="form-control mb-2"
                 onChange={(e) => setCourse({ ...course, name: e.target.value })} />
          <textarea value={course.description} 
                    className="form-control"
                    onChange={(e) => setCourse({ ...course, description: e.target.value })} />
        </>
      )}

      {currentUser?.role === "STUDENT" && (
        <button
          className="btn btn-primary float-end"
          onClick={() => setShowAllCourses(!showAllCourses)}
        >
          {showAllCourses ? "Show My Courses" : "Show All Courses"}
        </button>
      )}
      
      <hr />
      <h2 id="wd-dashboard-published">
        {currentUser?.role === "STUDENT" 
          ? (showAllCourses ? "All Courses" : "My Courses")
          : "Published Courses"} ({displayedCourses.length})
      </h2>
      <hr />

      <div id="wd-dashboard-courses" className="row">
        <div className="row row-cols-1 row-cols-md-5 g-4">
          {displayedCourses.map((course) => (
            <div key={course._id} className="wd-dashboard-course col" style={{ width: "300px" }}>
              <div className="card rounded-3 overflow-hidden">
                <img src={course.image} alt={course.name} height="160" className="card-img-top"/>
                <div className="card-body">
                  <span className="wd-dashboard-course-link" 
                        style={{ textDecoration: "none", color: "navy", fontWeight: "bold" }}>
                    {course.name}
                  </span>
                  <p className="wd-dashboard-course-title card-text" 
                     style={{ maxHeight: 53, overflow: "hidden" }}>
                    {course.description}
                  </p>

                  {currentUser?.role === "STUDENT" ? (
                    <>
                      {isEnrolled(course._id) && (
                        <Link to={`/Kanbas/Courses/${course._id}/Home`} 
                              className="btn btn-primary me-2">
                          Go to Course
                        </Link>
                      )}
                      <button
                        className={`btn ${isEnrolled(course._id) ? 'btn-danger' : 'btn-success'} float-end`}
                        onClick={(event) => {
                          event.preventDefault();
                          handleEnrollment(course._id);
                        }}
                      >
                        {isEnrolled(course._id) ? 'Unenroll' : 'Enroll'}
                      </button>
                    </>
                  ) : (
                    <>
                      <Link to={`/Kanbas/Courses/${course._id}/Home`} 
                            className="btn btn-primary">Go</Link>
                      <button onClick={(event) => {
                        event.preventDefault();
                        deleteCourse(course._id);
                      }} 
                      className="btn btn-danger float-end"
                      id="wd-delete-course-click">
                        Delete
                      </button>
                      <button id="wd-edit-course-click"
                        onClick={(event) => {
                          event.preventDefault();
                          setCourse(course);
                        }}
                        className="btn btn-warning me-2 float-end">
                        Edit
                      </button>
                    </>
                  )}
                </div>
              </div>
            </div>
          ))}
        </div>
      </div>
    </div>
  );
}